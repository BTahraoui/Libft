#include "libft.h"

char	*ft_strdup(const char *s)
{
	char	*copy;
	size_t	s_len;
	size_t	i;

	i = 0;
	s_len = ft_strlen(s);
	if (!s)
		return (NULL);
	copy = malloc((s_len + 1) * sizeof(char));
	if (copy == NULL)
		return (NULL);
	while (s[i])
	{
		copy[i] = s[i];
		i++;
	}
	copy[i] = '\0';
	return (copy);
}
